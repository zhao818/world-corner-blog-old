VOL2_LEAD = """主书立论，番外验证。接下来的十三个故事，来自文学、来自童话、来自一些真实的生命——它们不讲道理，只给证据：验证爱长什么样，幸福长什么样。"""

# 正文中间的广播衔接语 → 书面语(逐条替换)
BODY_FIX = [
    ("我们下一集接着讲", "我们下一章接着讲"),
    ("下一集，我们把镜头拉远", "下一章，我们把镜头拉远"),
    ("下一集，我要摆一个擂台", "下一章，我要摆一个擂台"),
    ("在下一集开始之前", "在这里"),
    ("你可能会觉得，这一集太沉重了", "你可能会觉得，这一章太沉重了"),
    ("所以，这集不干别的", "所以，这一章不干别的"),
]


def split_paras(text):
    return [p.strip() for p in re.split(r"\n\s*\n", text) if p.strip()]


def chapter_title(fname):
    """08-大逃离.md → 08 大逃离"""
    stem = os.path.splitext(fname)[0]
    return re.sub(r"^(\d+)-", r"\1 ", stem)


def main():
    files = sorted(glob.glob(os.path.join(SRC_DIR, "*.md")))
    print("发现文稿:", len(files), "篇")
    assert len(files) == 31, "篇数不对!"

    out = [PREFACE, "# 卷一 幸福的内在", "从“为什么空”问起，到“怎么建”给出三根柱石，再到“根”追到思想来源——卷一讲道理，讲一个完整的闭环。"]

    leftovers = []  # 处理完仍残留口播的篇
    for i, fp in enumerate(files):
        stem = os.path.splitext(os.path.basename(fp))[0]
        rule = REWRITE.get(stem)
        if rule is None:
            leftovers.append("%s: 无改写规则!" % stem)
            continue
        text = open(fp, encoding="utf-8").read()
        paras = split_paras(text)

        # 首段
        head = rule.get("head")
        if head is None:
            pass  # 保留原文
        else:
            paras[0] = head

        # 末段
        tail = rule.get("tail")
        if tail is False:
            paras = paras[:-1]
        elif tail is not None:
            paras[-1] = tail

        # 卷二切换:19 前插卷首导读
        if stem == "19-纯真之眼":
            out.append("# 卷二 幸福的验证")
            out.append(VOL2_LEAD)

        # 章节
        out.append("## " + chapter_title(os.path.basename(fp)))
        body = "\n\n".join(paras)
        for a, b in BODY_FIX:
            body = body.replace(a, b)
        out.append(body)

        # 校验残留口播
        for w in ("上一集", "下一集", "这一集", "上集"):
            if w in body:
                leftovers.append("%s: 残留「%s」" % (stem, w))
                break

    text = "\n\n".join(out) + "\n"
    open(DST, "w", encoding="utf-8").write(text)

    # 汇总校验
    total_chars = len(text)
    print("输出:", DST)
    print("总字数(含标题):", total_chars)
    if leftovers:
        print("\n⚠️ 需人工检查:")
        for l in leftovers:
            print("  -", l)
    else:
        print("✅ 无口播残留")


if __name__ == "__main__":
    main()
